import { z } from "zod";

// Money is integer PAISE (₹200 = 20000).
export const manualDepositSchema = z
  .object({
    userId: z.string().uuid("Invalid member"),
    purpose: z.enum(["MONTHLY_DEPOSIT", "ADDITIONAL_DEPOSIT"]),
    amountPaise: z
      .number()
      .int("Amount must be a whole number of paise")
      .min(100, "Minimum deposit is ₹1")
      .max(100_000_000, "Maximum deposit is ₹10,00,000"),
    method: z.enum(["UPI", "CASH", "BANK_TRANSFER", "OTHER"]),
    // UTR / bank transaction ID. Required for everything except cash.
    paymentReference: z
      .string()
      .trim()
      .min(6)
      .max(64)
      .regex(/^[A-Za-z0-9_-]+$/, "Use letters, numbers, - and _ only")
      .optional(),
    // Evidence is mandatory: this is what auditors will read.
    evidenceNote: z.string().trim().min(5, "Describe the evidence (e.g. 'UPI screenshot seen')").max(500),
    evidenceUrl: z
      .string()
      .trim()
      .url()
      .max(500)
      .refine((u) => u.startsWith("https://"), "Evidence link must start with https://")
      .optional(),
    // When the money actually arrived (defaults to now).
    paidAt: z.coerce.date().optional(),
    periodYear: z.number().int().min(2020).max(2100).optional(),
    periodMonth: z.number().int().min(1).max(12).optional(),
    // Generated by the frontend once per form submission. Makes retries safe.
    clientRequestId: z
      .string()
      .trim()
      .min(8)
      .max(100)
      .regex(/^[A-Za-z0-9_-]+$/),
  })
  .refine((v) => v.method === "CASH" || !!v.paymentReference, {
    message: "A payment reference (UTR / transaction ID) is required for non-cash deposits",
    path: ["paymentReference"],
  })
  .refine((v) => (v.periodYear === undefined) === (v.periodMonth === undefined), {
    message: "Provide both periodYear and periodMonth, or neither",
    path: ["periodMonth"],
  })
  .refine((v) => v.purpose === "MONTHLY_DEPOSIT" || v.periodYear === undefined, {
    message: "A period only applies to monthly deposits",
    path: ["periodYear"],
  });

export const periodQuerySchema = z
  .object({
    year: z.coerce.number().int().min(2020).max(2100).optional(),
    month: z.coerce.number().int().min(1).max(12).optional(),
  })
  .refine((v) => (v.year === undefined) === (v.month === undefined), "Provide both year and month, or neither");

export const pageQuerySchema = z.object({
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(20),
});

export type ManualDepositInput = z.infer<typeof manualDepositSchema>;
export type PeriodQuery = z.infer<typeof periodQuerySchema>;
export type PageQuery = z.infer<typeof pageQuerySchema>;
